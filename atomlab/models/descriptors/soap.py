"""SOAP power spectrum with analytic derivatives.

The Smooth Overlap of Atomic Positions descriptor represents the neighbour
density of atom ``i`` as a sum of Gaussians of width ``sigma_atom`` centred on
its neighbours,

.. math::

    \\rho_i(\\mathbf{r}) = \\sum_{j \\ne i} w_{s_j} f_c(r_{ij})
        \\exp\\!\\big[-\\alpha |\\mathbf{r} - \\mathbf{d}_{ij}|^2\\big],
    \\qquad \\alpha = \\frac{1}{2\\sigma_{\\rm atom}^2},

expands it in an orthonormal radial basis :math:`g_n(r)` and real spherical
harmonics :math:`Y_{lm}(\\hat{\\mathbf{r}})`,

.. math::  c^{(i)}_{nlm} = \\int g_n(r) Y_{lm}(\\hat{\\mathbf{r}})
                            \\rho_i(\\mathbf{r})\\, \\mathrm{d}^3 r,

and contracts the ``m`` index to obtain the rotationally invariant power
spectrum

.. math::  p^{(i)}_{n n' l} = \\frac{1}{\\sqrt{2l+1}}
                              \\sum_{m=-l}^{l} c^{(i)}_{nlm} c^{(i)}_{n'lm}.

Why this file is written the way it is
--------------------------------------

*The radial integral is done by quadrature, and the descriptor is defined to be
the quadrature sum.*  Using the plane-wave-like expansion of a displaced
Gaussian,

.. math::  e^{-\\alpha|\\mathbf{r}-\\mathbf{d}|^2} = e^{-\\alpha(r^2+d^2)}
           \\sum_{lm} 4\\pi\\, i_l(2\\alpha r d)\\, Y_{lm}(\\hat{\\mathbf{r}})
           Y_{lm}(\\hat{\\mathbf{d}}),

with :math:`i_l` the modified spherical Bessel function of the first kind, the
angular integral is exact and only a one-dimensional radial integral

.. math::  R_{nl}(d) = 4\\pi \\int_0^{r_{\\rm cut}} r^2 g_n(r)\\,
           e^{-\\alpha(r^2+d^2)} i_l(2\\alpha r d)\\, \\mathrm{d}r

remains.  There is no closed form for a polynomial ``g_n``, so it is evaluated
with fixed Gauss-Legendre quadrature.  Crucially the descriptor is *defined* as
that quadrature sum rather than as the exact integral it approximates, and the
analytic derivative is the exact derivative of the same sum.  Quadrature error
therefore shifts the feature definition slightly but never breaks the
derivative identity, which is the property the whole study depends on.

*The angular derivative goes through real solid harmonics, not through
spherical coordinates.*  ``dY_lm/dtheta`` has a coordinate singularity at
``theta = 0`` (the ``1/sin(theta)`` in ``dphi``), and neighbours sit on the
polar axis routinely in a cubic crystal.  Writing ``Y_lm(d_hat) = S_lm(d)/r^l``
with :math:`S_lm` the *real solid harmonic* -- a homogeneous polynomial in
``(x, y, z)`` of degree ``l`` -- makes the cartesian gradient a polynomial
identity that is regular everywhere except ``r = 0``.  The polynomial and its
gradient are generated by the same recurrence, carrying the gradient along, so
value and derivative cannot drift apart.

*Normalisation acquires a projection term.*  With
:math:`\\hat{p} = p / \\lVert p \\rVert`,

.. math::  \\frac{\\partial \\hat p}{\\partial x}
           = \\frac{1}{\\lVert p \\rVert}
             \\Big( \\mathbb{1} - \\hat p \\hat p^{\\mathsf T} \\Big)
             \\frac{\\partial p}{\\partial x} .

The projector is easy to forget, and forgetting it produces a descriptor
derivative that is wrong only in the component along ``p`` itself -- a small,
smooth error that a fit happily absorbs into its coefficients while quietly
corrupting every force.  That is exactly the failure mode this repository is
about, so the term is applied explicitly in :meth:`SOAP.compute` and checked
against finite differences in ``tests/test_soap.py``.

Cost
----

Defaults are ``n_max = 4``, ``l_max = 3``: 4 radial channels and ``l = 0..3``
give ``4 * n_max (n_max + 1) / 2 = 40`` invariant features.  This is far
smaller than a production SOAP (``n_max = 8-12``, ``l_max = 6-9``, thousands of
features) and is a deliberate scaling-down for a 4-core CPU budget: the study
needs a descriptor whose *error structure* is representative, not one whose
basis-set convergence is publishable.
"""

