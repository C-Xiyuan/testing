def polynomial_radial_basis(n_max: int, r_cut: float) -> np.ndarray:
    """Orthonormalising transform for the GAP polynomial radial basis.

    The primitive basis is ``phi_n(r) = (r_cut - r)**(n + 2)`` for
    ``n = 1 .. n_max``.  Two properties make it the standard GAP choice and are
    worth stating explicitly:

    * every ``phi_n`` and its first two derivatives vanish **exactly** at
      ``r_cut`` (the exponent is at least 3), so nothing has to be smoothed by
      hand at the cutoff;
    * the Gram matrix under the radial measure ``r^2 dr`` is available in closed
      form,

      ``S_nm = int_0^rc r^2 phi_n phi_m dr
             = rc^(n+m+7) * 2 / ((n+m+5)(n+m+6)(n+m+7))``

      so the orthonormalisation carries no quadrature error of its own.

    Parameters
    ----------
    n_max : int
        Number of radial functions, ``>= 1``.
    r_cut : float
        Cutoff radius in angstrom.

    Returns
    -------
    ndarray, shape (n_max, n_max)
        The matrix ``W = S^(-1/2)`` with ``g_n(r) = sum_m W[n, m] phi_{m+1}(r)``
        satisfying ``int_0^rc r^2 g_n g_n' dr = delta_{nn'}``.  Units of
        ``g_n`` are ``A^(-3/2)``.

    Notes
    -----
    ``S`` is a Hilbert-like matrix and its condition number grows quickly with
    ``n_max``; at the default ``n_max = 4`` it is ~1e4, which double precision
    handles comfortably.  A warning-free ``n_max`` above ~10 would need a
    genuinely orthogonal primitive basis instead, and this project has no use
    for one.
    """
    n_max = int(n_max)
    if n_max < 1:
        raise ValueError(f"n_max must be >= 1, got {n_max}")
    r_cut = float(r_cut)
    if r_cut <= 0.0:
        raise ValueError(f"r_cut must be > 0 A, got {r_cut}")

    idx = np.arange(1, n_max + 1)
    k = idx[:, None] + idx[None, :]  # n + m
    gram = r_cut ** (k + 7.0) * 2.0 / ((k + 5.0) * (k + 6.0) * (k + 7.0))
    # Symmetric positive definite by construction; use the eigendecomposition
    # rather than a Cholesky inverse so that near-degenerate directions are
    # visible as tiny eigenvalues instead of a spurious failure.
    evals, evecs = np.linalg.eigh(gram)
    if np.any(evals <= 0.0):
        raise np.linalg.LinAlgError(
            f"radial Gram matrix is not positive definite for n_max={n_max}; "
            "the polynomial basis has become numerically degenerate"
        )
    return (evecs / np.sqrt(evals)) @ evecs.T


def _radial_basis_values(n_max: int, r_cut: float, weights: np.ndarray, r: np.ndarray):
    """Evaluate ``g_n(r)`` on a grid.

    Parameters
    ----------
    n_max, r_cut : see :func:`polynomial_radial_basis`
    weights : ndarray, shape (n_max, n_max)
        The transform from :func:`polynomial_radial_basis`.
    r : ndarray, shape (Q,)
        Radii in angstrom.

    Returns
    -------
    ndarray, shape (n_max, Q)
        ``g_n(r_q)`` in ``A^(-3/2)``.
    """
    powers = np.arange(1, n_max + 1) + 2.0
    phi = np.power(np.maximum(r_cut - r, 0.0)[None, :], powers[:, None])
    return weights @ phi


