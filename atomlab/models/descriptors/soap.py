def _scaled_bessel_i(l_max: int, u: np.ndarray) -> np.ndarray:
    """``exp(-u) * i_l(u)`` for ``l = 0 .. l_max``, where ``i_l`` is modified
    spherical Bessel of the first kind.

    Parameters
    ----------
    l_max : int
        Highest order required.
    u : ndarray
        Non-negative arguments, ``u = 2 * alpha * r * d``.

    Returns
    -------
    ndarray, shape u.shape + (l_max + 1,)
        Dimensionless.

    Notes
    -----
    ``i_l(u) = sqrt(pi / 2u) I_{l+1/2}(u)`` grows like ``e^u / 2u``, which
    overflows double precision at ``u ~ 700``.  With ``alpha = 1/(2 sigma^2)``,
    ``sigma = 0.3 A`` and ``r = d = 5 A`` we already have ``u ~ 280``, so the
    unscaled function is not merely inelegant here but actually unusable.  The
    factor ``e^{-alpha(r^2+d^2)}`` that multiplies it in the SOAP integrand
    supplies exactly the compensating decay, and the two are combined
    analytically as ``e^{-alpha(r-d)^2} * [e^{-u} i_l(u)]`` before anything is
    evaluated numerically.  ``scipy.special.ive`` is the exponentially scaled
    modified Bessel function ``I_nu(u) e^{-|u|}``, so it delivers the bracket
    directly.
    """
    u = np.asarray(u, dtype=np.float64)
    # u = 0 makes the sqrt(pi/2u) prefactor singular even though the product is
    # finite; the floor is far below any physically reachable pair separation
    # times a quadrature node, and keeps the expression branch-free.
    u_safe = np.maximum(u, 1e-12)
    orders = np.arange(l_max + 1) + 0.5
    scaled = ive(orders, u_safe[..., None])
    return np.sqrt(0.5 * math.pi / u_safe)[..., None] * scaled


