def real_spherical_harmonic_scipy(l: int, m: int, directions: np.ndarray) -> np.ndarray:
    """Real spherical harmonic ``Y_lm`` evaluated with SciPy, for validation.

    Parameters
    ----------
    l : int
        Degree, ``l >= 0``.
    m : int
        Order, ``-l <= m <= l``.
    directions : ndarray, shape (P, 3)
        Cartesian vectors (angstrom, or any unit -- only the direction is
        used).  Must be nonzero.

    Returns
    -------
    ndarray, shape (P,)
        Dimensionless values of the real spherical harmonic, in the convention

        ``Y_l0     =            Y_l^0``
        ``Y_lm     = sqrt(2) (-1)^m Re Y_l^m``   (m > 0)
        ``Y_l,-m   = sqrt(2) (-1)^m Im Y_l^m``   (m > 0)

        with ``Y_l^m`` the complex harmonic.  The ``(-1)^m`` cancels the
        Condon-Shortley phase that SciPy includes, giving the phase-free
        convention used by the SOAP literature.

    Notes
    -----
    Uses ``scipy.special.sph_harm_y(n, m, theta, phi)`` with ``theta`` the
    **polar** angle and ``phi`` the azimuth -- the modern signature.  The legacy
    ``scipy.special.sph_harm`` (which took the arguments in the opposite order)
    was removed in SciPy 1.17, so it must not be used here.

    This routine is *not* used in the hot path; it is the independent reference
    that :func:`real_solid_harmonics` is checked against, because a wrong
    spherical-harmonic convention is precisely the bug that a rotational
    invariance test is designed to catch.
    """
    d = np.asarray(directions, dtype=np.float64).reshape(-1, 3)
    r = np.linalg.norm(d, axis=1)
    if np.any(r == 0.0):
        raise ValueError("cannot evaluate a spherical harmonic on a zero vector")
    theta = np.arccos(np.clip(d[:, 2] / r, -1.0, 1.0))  # polar angle in [0, pi]
    phi = np.arctan2(d[:, 1], d[:, 0])  # azimuth; sph_harm_y is 2*pi periodic in it
    y = sph_harm_y(int(l), int(abs(m)), theta, phi)
    if m == 0:
        return np.real(y)
    sign = (-1.0) ** abs(m)
    if m > 0:
        return math.sqrt(2.0) * sign * np.real(y)
    return math.sqrt(2.0) * sign * np.imag(y)


def _lm_index(l: int, m: int) -> int:
    """Flat index of ``(l, m)`` in the ``(l_max+1)**2`` packed ordering.

    Layout is ``l`` major, ``m`` running ``-l .. +l``, i.e. ``l*l + (m + l)``.
    """
    return l * l + (m + l)


def real_solid_harmonics(
    d: np.ndarray, l_max: int, *, gradient: bool = True
) -> tuple[np.ndarray, np.ndarray | None]:
    """Real solid harmonics ``S_lm(d) = |d|^l Y_lm(d_hat)`` and their gradients.

    Parameters
    ----------
    d : ndarray, shape (P, 3)
        Cartesian vectors in angstrom.
    l_max : int
        Maximum degree, ``>= 0``.
    gradient : bool
        Also return ``dS_lm / dd`` (cartesian).

    Returns
    -------
    S : ndarray, shape (P, (l_max+1)**2)
        Solid harmonics in units of ``A**l``, packed by :func:`_lm_index`.
    dS : ndarray, shape (P, (l_max+1)**2, 3) or None
        Cartesian gradient in units of ``A**(l-1)``.

    Notes
    -----
    Everything here is polynomial, hence regular at the poles ``x = y = 0``
    where the spherical-coordinate derivatives of ``Y_lm`` are singular.  The
    construction factors the solid harmonic as

    ``S_lm = K_lm * Pi_l^|m|(z, r^2) * {C_|m|(x,y) if m >= 0 else S_|m|(x,y)}``

    with ``C_m + i S_m = (x + i y)^m`` (built by the two-term recurrence
    ``C_m = x C_{m-1} - y S_{m-1}``, ``S_m = x S_{m-1} + y C_{m-1}``) and
    ``Pi`` the homogenised associated-Legendre polynomial obeying

    ``Pi_m^m = (2m-1)!!``,
    ``Pi_{m+1}^m = (2m+1) (2m-1)!! z``,
    ``(l-m) Pi_l^m = (2l-1) z Pi_{l-1}^m - (l+m-1) r^2 Pi_{l-2}^m``.

    The normalisation ``K_lm = sqrt((2l+1)/(4 pi) (l-|m|)!/(l+|m|)!)`` times
    ``sqrt(2)`` for ``m != 0`` reproduces the Condon-Shortley-free real
    harmonics of :func:`real_spherical_harmonic_scipy` exactly.

    Gradients are propagated through every recurrence step rather than derived
    by a closed formula, so the returned derivative is the exact derivative of
    the returned value by construction.
    """
    l_max = int(l_max)
    if l_max < 0:
        raise ValueError(f"l_max must be >= 0, got {l_max}")
    d = np.ascontiguousarray(np.asarray(d, dtype=np.float64).reshape(-1, 3))
    n_pairs = d.shape[0]
    x, y, z = d[:, 0], d[:, 1], d[:, 2]
    r2 = x * x + y * y + z * z

    n_lm = (l_max + 1) ** 2
    out = np.zeros((n_pairs, n_lm))
    dout = np.zeros((n_pairs, n_lm, 3)) if gradient else None

    # (x + i y)^m, split into real (Cm) and imaginary (Sm) parts.
    cm = np.zeros((l_max + 1, n_pairs))
    sm = np.zeros((l_max + 1, n_pairs))
    dcm = np.zeros((l_max + 1, n_pairs, 3))
    dsm = np.zeros((l_max + 1, n_pairs, 3))
    cm[0] = 1.0
    for m in range(1, l_max + 1):
        cm[m] = x * cm[m - 1] - y * sm[m - 1]
        sm[m] = x * sm[m - 1] + y * cm[m - 1]
        if gradient:
            dcm[m] = x[:, None] * dcm[m - 1] - y[:, None] * dsm[m - 1]
            dcm[m, :, 0] += cm[m - 1]
            dcm[m, :, 1] -= sm[m - 1]
            dsm[m] = x[:, None] * dsm[m - 1] + y[:, None] * dcm[m - 1]
            dsm[m, :, 0] += sm[m - 1]
            dsm[m, :, 1] += cm[m - 1]

    for m in range(0, l_max + 1):
        # (2m - 1)!!, with the empty product equal to 1 for m = 0.
        dfact = 1.0
        for k in range(1, 2 * m, 2):
            dfact *= k

        pi_lm2 = None
        dpi_lm2 = None
        pi_lm1 = np.full(n_pairs, dfact)  # l = m
        dpi_lm1 = np.zeros((n_pairs, 3))

        for l in range(m, l_max + 1):
            if l == m:
                pi = pi_lm1
                dpi = dpi_lm1
            elif l == m + 1:
                pi = (2 * m + 1) * dfact * z
                dpi = np.zeros((n_pairs, 3))
                dpi[:, 2] = (2 * m + 1) * dfact
            else:
                inv = 1.0 / (l - m)
                pi = ((2 * l - 1) * z * pi_lm1 - (l + m - 1) * r2 * pi_lm2) * inv
                if gradient:
                    dpi = (
                        (2 * l - 1) * z[:, None] * dpi_lm1
                        - (l + m - 1) * (r2[:, None] * dpi_lm2 + 2.0 * d * pi_lm2[:, None])
                    ) * inv
                    dpi[:, 2] += (2 * l - 1) * pi_lm1 * inv
                else:
                    dpi = None

            # K_lm = sqrt((2l+1)/(4 pi) * (l-m)!/(l+m)!), with sqrt(2) for m != 0.
            norm = math.sqrt(
                (2 * l + 1)
                / (4.0 * math.pi)
                * math.factorial(l - m)
                / math.factorial(l + m)
            )
            if m > 0:
                norm *= math.sqrt(2.0)

            idx = _lm_index(l, m)
            out[:, idx] = norm * pi * cm[m]
            if gradient:
                dout[:, idx, :] = norm * (dpi * cm[m][:, None] + pi[:, None] * dcm[m])
            if m > 0:
                idx_neg = _lm_index(l, -m)
                out[:, idx_neg] = norm * pi * sm[m]
                if gradient:
                    dout[:, idx_neg, :] = norm * (
                        dpi * sm[m][:, None] + pi[:, None] * dsm[m]
                    )

            pi_lm2, dpi_lm2 = pi_lm1, dpi_lm1
            pi_lm1, dpi_lm1 = pi, dpi

    return out, dout


