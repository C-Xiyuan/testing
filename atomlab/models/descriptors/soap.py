class SOAP(Descriptor):
    """SOAP power spectrum with exact analytic position derivatives.

    Parameters
    ----------
    r_cut : float
        Cutoff radius in angstrom.  Default 5.0.
    n_max : int
        Number of orthonormal radial basis functions.  Default 4.
    l_max : int
        Maximum spherical-harmonic degree; ``l`` runs ``0 .. l_max``.
        Default 3.
    sigma_atom : float
        Width in angstrom of the Gaussian placed on each neighbour.  Default
        0.5.  Smaller values sharpen the density and demand more quadrature
        nodes; larger values wash out radial structure.
    n_quadrature : int
        Number of Gauss-Legendre nodes used for the radial overlap integral
        ``R_nl``.  Default 48.  This controls how faithfully the features
        approximate the ideal SOAP integral; it has **no** effect on the
        exactness of the derivatives, on rotational invariance, or on any other
        symmetry, because the descriptor is defined as the quadrature sum.
    normalize : bool
        Scale each atom's feature vector to unit Euclidean length.  Default
        True.  See the module docstring for the projection term this adds to
        the derivative.
    species_weights : sequence of float, optional
        Multiplicative weight per species index applied to that species'
        contribution to the density.  ``None`` (default) weights every
        neighbour equally, which is what the single-species systems in this
        study need.  This is the cheap way to carry chemistry: a proper
        multi-species SOAP would give each species its own set of ``c_nlm``
        channels and square the feature count.
    name : str
        Identifier used in tables and figures.

    Attributes
    ----------
    cutoff : float
        Interaction range in angstrom, equal to ``r_cut``.
    n_features : int
        ``(l_max + 1) * n_max * (n_max + 1) / 2``.  For the defaults
        ``n_max = 4``, ``l_max = 3`` this is 40.

    Notes
    -----
    Feature ordering is ``l`` major, then the upper triangle ``n <= n'`` in
    row-major order:  ``(l=0, n=1, n'=1), (l=0, n=1, n'=2), ...``.  Off-diagonal
    terms ``n < n'`` appear once and are *not* multiplied by ``sqrt(2)``; the
    resulting vector is still a complete set of invariants and any constant
    per-feature rescaling is absorbed by the model that consumes it.

    Units: ``g_n`` is normalised against the measure ``r^2 dr`` and so carries
    ``A^(-3/2)``; integrating it against the (dimensionless) density over
    ``d^3 r`` leaves ``c_nlm`` in ``A^(3/2)`` and the unnormalised power
    spectrum in ``A^3``.  After ``normalize=True`` the features are
    dimensionless.
    """

    def __init__(
        self,
        r_cut: float = 5.0,
        n_max: int = 4,
        l_max: int = 3,
        sigma_atom: float = 0.5,
        *,
        n_quadrature: int = 48,
        normalize: bool = True,
        species_weights: Sequence[float] | None = None,
        name: str = "soap",
        chunk_size: int = 4096,
    ) -> None:
        self.cutoff = float(r_cut)
        if self.cutoff <= 0.0:
            raise ValueError(f"r_cut must be > 0 A, got {r_cut}")
        self.n_max = int(n_max)
        self.l_max = int(l_max)
        if self.n_max < 1:
            raise ValueError(f"n_max must be >= 1, got {n_max}")
        if self.l_max < 0:
            raise ValueError(f"l_max must be >= 0, got {l_max}")
        self.sigma_atom = float(sigma_atom)
        if self.sigma_atom <= 0.0:
            raise ValueError(f"sigma_atom must be > 0 A, got {sigma_atom}")
        self.n_quadrature = int(n_quadrature)
        if self.n_quadrature < 4:
            raise ValueError(f"n_quadrature must be >= 4, got {n_quadrature}")
        self.normalize = bool(normalize)
        self.species_weights = (
            None if species_weights is None else np.asarray(species_weights, dtype=np.float64)
        )
        self.name = str(name)
        self.chunk_size = int(chunk_size)
        if self.chunk_size < 1:
            raise ValueError(f"chunk_size must be >= 1, got {chunk_size}")

        self.alpha = 0.5 / (self.sigma_atom * self.sigma_atom)

        # -- fixed quadrature grid and radial basis, built once ------------
        nodes, weights = np.polynomial.legendre.leggauss(self.n_quadrature)
        self._r_quad = 0.5 * self.cutoff * (nodes + 1.0)
        w_quad = 0.5 * self.cutoff * weights
        self._basis_transform = polynomial_radial_basis(self.n_max, self.cutoff)
        g = _radial_basis_values(self.n_max, self.cutoff, self._basis_transform, self._r_quad)
        # Fold the measure r^2 dr and the 4*pi of the Gaussian expansion into
        # the weights, so the pair loop is a single contraction.
        self._quad_weights = (4.0 * math.pi) * g * (w_quad * self._r_quad**2)[None, :]

        # -- feature index bookkeeping -------------------------------------
        pairs = [(n, m) for n in range(self.n_max) for m in range(n, self.n_max)]
        self._pair_n = np.array([p[0] for p in pairs], dtype=np.intp)
        self._pair_m = np.array([p[1] for p in pairs], dtype=np.intp)
        self._n_features = (self.l_max + 1) * len(pairs)

    # -- introspection ----------------------------------------------------

    @property
    def n_features(self) -> int:
        """Descriptor dimension per atom."""
        return self._n_features

    def feature_labels(self) -> list[str]:
        """Human-readable ``(l, n, n')`` label for every feature, in order."""
        out: list[str] = []
        for l in range(self.l_max + 1):
            for n, m in zip(self._pair_n, self._pair_m):
                out.append(f"l{l}_n{int(n) + 1}_n{int(m) + 1}")
        return out

    def __repr__(self) -> str:  # pragma: no cover - cosmetic
        return (
            f"SOAP(r_cut={self.cutoff}, n_max={self.n_max}, l_max={self.l_max}, "
            f"sigma_atom={self.sigma_atom}, n_features={self.n_features})"
        )

    # -- pieces of the calculation ----------------------------------------

    def _cutoff_function(self, r: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        """Cosine cutoff ``0.5 (1 + cos(pi r / rc))`` and its derivative.

        Both the function and its first derivative vanish at ``r_cut``, so a
        neighbour entering or leaving the sphere contributes no discontinuity to
        the descriptor or to the force.  The radial basis vanishes at ``r_cut``
        too, but that does not help here: ``R_nl(d)`` is an *integral* over the
        basis, not an evaluation of it, and is nonzero at ``d = r_cut``.

        Returns arrays of shape ``r.shape``; ``f`` dimensionless, ``df`` in
        ``1/A``.
        """
        s = math.pi / self.cutoff
        f = 0.5 * (1.0 + np.cos(s * r))
        df = -0.5 * s * np.sin(s * r)
        outside = r >= self.cutoff
        f = np.where(outside, 0.0, f)
        df = np.where(outside, 0.0, df)
        return f, df

    def _radial_overlap(self, r_pair: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        """``R_nl(d)`` and ``dR_nl/dd`` for a batch of pair distances.

        Parameters
        ----------
        r_pair : ndarray, shape (P,)
            Pair distances ``d`` in angstrom.

        Returns
        -------
        R : ndarray, shape (P, n_max, l_max + 1)
            Radial overlap integrals, units ``A^(3/2)``.
        dR : ndarray, shape (P, n_max, l_max + 1)
            ``dR/dd`` in ``A^(1/2)``.

        Notes
        -----
        The integrand is written as

        ``r^2 g_n(r) * exp(-alpha (r - d)^2) * h_l(2 alpha r d)``,
        ``h_l(u) = e^{-u} i_l(u)``,

        which is the numerically safe regrouping described in
        :func:`_scaled_bessel_i`.  Differentiating under the integral sign,

        ``d/dd [exp(-alpha (r-d)^2) h_l] =
             exp(-alpha (r-d)^2) * 2 alpha [ (r - d) h_l + r h_l' ]``

        and ``h_l'(u) = [l h_{l-1}(u) + (l+1) h_{l+1}(u)] / (2l+1) - h_l(u)``,
        which follows from ``i_l' = [l i_{l-1} + (l+1) i_{l+1}]/(2l+1)`` and the
        product rule on the ``e^{-u}`` factor.  This is why ``h`` is evaluated
        up to order ``l_max + 1``.
        """
        alpha = self.alpha
        rq = self._r_quad  # (Q,)
        d = r_pair[:, None]  # (P, 1)

        gauss = np.exp(-alpha * (rq[None, :] - d) ** 2)  # (P, Q)
        u = (2.0 * alpha) * rq[None, :] * d  # (P, Q)
        h = _scaled_bessel_i(self.l_max + 1, u)  # (P, Q, l_max + 2)

        ell = np.arange(self.l_max + 1)
        h_lo = np.concatenate([np.zeros(h.shape[:-1] + (1,)), h[..., : self.l_max]], axis=-1)
        dh = (
            ell * h_lo + (ell + 1.0) * h[..., 1 : self.l_max + 2]
        ) / (2.0 * ell + 1.0) - h[..., : self.l_max + 1]

        core = gauss[..., None] * h[..., : self.l_max + 1]  # (P, Q, L+1)
        dcore = gauss[..., None] * (
            (2.0 * alpha)
            * (
                (rq[None, :, None] - d[..., None]) * h[..., : self.l_max + 1]
                + rq[None, :, None] * dh
            )
        )

        r_nl = np.einsum("nq,pql->pnl", self._quad_weights, core, optimize=True)
        dr_nl = np.einsum("nq,pql->pnl", self._quad_weights, dcore, optimize=True)
        return r_nl, dr_nl

    def _pair_expansion(self, dvec: np.ndarray, r: np.ndarray, derivatives: bool):
        """Per-pair contribution to ``c_nlm`` and its cartesian gradient.

        Parameters
        ----------
        dvec : ndarray, shape (P, 3)
            Pair displacement vectors ``d_ij = r_j - r_i`` in angstrom.
        r : ndarray, shape (P,)
            ``|d_ij|`` in angstrom.
        derivatives : bool

        Returns
        -------
        contrib : ndarray, shape (P, n_max, (l_max+1)**2)
            ``A_nl(r) * Y_lm(d_hat)`` in ``A^(3/2)``, where
            ``A_nl = R_nl * f_cut``.
        dcontrib : ndarray, shape (P, n_max, (l_max+1)**2, 3) or None
            ``d/dd`` of the above, in ``A^(1/2)``.

        Notes
        -----
        The whole point of the solid-harmonic route appears here.  Writing
        ``A_nl(r) Y_lm(d_hat) = B_nl(r) S_lm(d)`` with ``B_nl = A_nl / r^l``,

        ``grad [B_nl S_lm] = B_nl'(r) (d / r) S_lm(d) + B_nl(r) grad S_lm(d)``

        which never divides by ``sin(theta)`` and is therefore finite for every
        neighbour direction including the poles.
        """
        r_nl, dr_nl = self._radial_overlap(r)  # (P, n, L+1)
        f_cut, df_cut = self._cutoff_function(r)

        a_nl = r_nl * f_cut[:, None, None]
        da_nl = dr_nl * f_cut[:, None, None] + r_nl * df_cut[:, None, None]

        # B_nl = A_nl / r^l  and  B_nl' = A_nl'/r^l - l A_nl / r^(l+1).
        ell = np.arange(self.l_max + 1)
        inv_rl = r[:, None, None] ** (-ell[None, None, :].astype(np.float64))
        b_nl = a_nl * inv_rl
        db_nl = (da_nl - ell[None, None, :] * a_nl / r[:, None, None]) * inv_rl

        solid, dsolid = real_solid_harmonics(dvec, self.l_max, gradient=derivatives)

        # Expand the (l) axis of B to the packed (l, m) axis.
        l_of_lm = np.concatenate([np.full(2 * l + 1, l) for l in range(self.l_max + 1)])
        b_lm = b_nl[:, :, l_of_lm]  # (P, n, LM)
        contrib = b_lm * solid[:, None, :]

        if not derivatives:
            return contrib, None

        db_lm = db_nl[:, :, l_of_lm]
        dhat = dvec / r[:, None]
        dcontrib = (
            db_lm[..., None] * solid[:, None, :, None] * dhat[:, None, None, :]
            + b_lm[..., None] * dsolid[:, None, :, :]
        )
        return contrib, dcontrib

    # -- the public entry point -------------------------------------------

    def compute(
        self, configuration: Configuration, *, derivatives: bool = True
    ) -> DescriptorOutput:
        """Featurise every atom of ``configuration``.

        Parameters
        ----------
        configuration : Configuration
            Geometry; not modified.
        derivatives : bool
            Also return ``dp/dr`` in the sparse pair layout of
            :class:`~atomlab.models.base.DescriptorOutput`.

        Returns
        -------
        DescriptorOutput
            ``features`` is ``(N, n_features)``; with ``normalize=True`` it is
            dimensionless, otherwise ``A^3``.  ``derivatives`` is
            ``(P + N, n_features, 3)`` in ``1/A`` (or ``A^2`` unnormalised):
            one block per neighbour pair, giving ``dp_i / dr_j``, followed by
            one block per atom giving the self term ``dp_i / dr_i``.

        Notes
        -----
        A pair ``(i, j)`` seen through several periodic images appears several
        times in the pair list, and the corresponding derivative blocks simply
        appear several times as well; the assembly in
        :meth:`DescriptorOutput.forces_from_energy_gradient` uses ``np.add.at``
        and therefore sums them, which is exactly right.

        Atoms with no neighbours inside the cutoff get a zero feature vector.
        With ``normalize=True`` that vector cannot be scaled to unit length, so
        it is left at zero rather than being divided by zero, and its
        derivatives are zero too.  This is a real state (an isolated atom in a
        dilute gas), not an error.
        """
        n_atoms = configuration.n_atoms
        nl = build_neighbor_list(configuration, self.cutoff, half=False)
        dvec, r = pair_vectors(configuration, nl)
        n_pairs = nl.n_pairs

        if n_pairs and np.any(r <= 0.0):
            raise ValueError(
                "SOAP found a pair at zero separation; two atoms are coincident, "
                "which makes the neighbour direction undefined"
            )

        n_lm = (self.l_max + 1) ** 2
        c_pair = np.zeros((n_pairs, self.n_max, n_lm))
        dc = np.zeros((n_pairs, self.n_max, n_lm, 3)) if derivatives else None

        weights = None
        if self.species_weights is not None and n_pairs:
            if int(configuration.species.max(initial=0)) >= self.species_weights.size:
                raise ValueError(
                    "species_weights is shorter than the number of species present"
                )
            weights = self.species_weights[configuration.species[nl.j]]

        for lo in range(0, n_pairs, self.chunk_size):
            hi = min(lo + self.chunk_size, n_pairs)
            contrib, dcontrib = self._pair_expansion(dvec[lo:hi], r[lo:hi], derivatives)
            if weights is not None:
                contrib = contrib * weights[lo:hi, None, None]
                if derivatives:
                    dcontrib = dcontrib * weights[lo:hi, None, None, None]
            c_pair[lo:hi] = contrib
            if derivatives:
                dc[lo:hi] = dcontrib

        c = segment_sum(c_pair, nl.i, n_atoms)
        features, dfeat = self._power_spectrum(c, dc, nl.i if n_pairs else None, derivatives)

        if not derivatives:
            return DescriptorOutput(features=features)

        # Self term: moving atom i moves the origin of every one of its
        # neighbour vectors, so dp_i/dr_i = -sum_p dp_i/dd_p.  A self-image
        # pair (i, i, shift) contributes +X as a neighbour and -X here, and the
        # two cancel exactly -- correct, because translating atom i translates
        # both ends of that vector and leaves the environment unchanged.
        self_deriv = -segment_sum(dfeat, nl.i, n_atoms)

        pair_i = np.concatenate([nl.i, np.arange(n_atoms, dtype=np.int32)])
        pair_j = np.concatenate([nl.j, np.arange(n_atoms, dtype=np.int32)])
        derivs = np.concatenate([dfeat, self_deriv], axis=0)
        return DescriptorOutput(
            features=features, derivatives=derivs, pair_i=pair_i, pair_j=pair_j
        )

    def _power_spectrum(self, c, dc, pair_i, derivatives):
        """Contract ``c_nlm`` into the invariant power spectrum.

        Parameters
        ----------
        c : ndarray, shape (N, n_max, (l_max+1)**2)
        dc : ndarray, shape (P, n_max, (l_max+1)**2, 3) or None
        pair_i : ndarray, shape (P,) or None
            Central atom of each pair, used to gather ``c`` per pair.
        derivatives : bool

        Returns
        -------
        features : ndarray, shape (N, n_features)
        dfeatures : ndarray, shape (P, n_features, 3) or None
        """
        n_atoms = c.shape[0]
        n_pair_terms = self._pair_n.size
        features = np.zeros((n_atoms, self.n_features))
        n_pairs = 0 if dc is None else dc.shape[0]
        dfeatures = np.zeros((n_pairs, self.n_features, 3)) if derivatives else None

        if derivatives and n_pairs:
            c_at_pair = c[pair_i]  # (P, n_max, LM)

        for l in range(self.l_max + 1):
            lo, hi = l * l, (l + 1) ** 2
            scale = 1.0 / math.sqrt(2 * l + 1)
            block = slice(l * n_pair_terms, (l + 1) * n_pair_terms)

            cl = c[:, :, lo:hi]  # (N, n_max, 2l+1)
            p_full = np.einsum("anm,aNm->anN", cl, cl, optimize=True) * scale
            features[:, block] = p_full[:, self._pair_n, self._pair_m]

            if derivatives and n_pairs:
                dcl = dc[:, :, lo:hi, :]  # (P, n_max, 2l+1, 3)
                ccl = c_at_pair[:, :, lo:hi]  # (P, n_max, 2l+1)
                # d/dx of sum_m c_n c_n' = (dc_n) c_n' + c_n (dc_n'); the second
                # term is the transpose of the first in (n, n').
                t = np.einsum("pnmk,pNm->pnNk", dcl, ccl, optimize=True)
                t = (t + t.transpose(0, 2, 1, 3)) * scale
                dfeatures[:, block, :] = t[:, self._pair_n, self._pair_m, :]

        if not self.normalize:
            return features, dfeatures

        norms = np.linalg.norm(features, axis=1)
        # An empty environment gives p = 0, which has no unit-length
        # representative; leave it at zero rather than manufacturing a direction.
        safe = np.where(norms > 0.0, norms, 1.0)
        unit = features / safe[:, None]
        if derivatives and n_pairs:
            # (1 - p_hat p_hat^T) / ||p||  --  the projection term that a
            # normalised descriptor's derivative acquires.
            u_at_pair = unit[pair_i]
            proj = np.einsum("pd,pdk->pk", u_at_pair, dfeatures, optimize=True)
            dfeatures = (
                dfeatures - u_at_pair[:, :, None] * proj[:, None, :]
            ) / safe[pair_i][:, None, None]
        return unit, dfeatures
