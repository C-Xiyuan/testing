def segment_sum(values: np.ndarray, segment: np.ndarray, n_segments: int) -> np.ndarray:
    """Sum ``values`` over contiguous runs of equal ``segment`` label.

    Parameters
    ----------
    values : ndarray, shape (P, ...)
        Rows to be accumulated.
    segment : ndarray, shape (P,)
        Segment label of each row.  Must be **sorted non-decreasing**; the
        neighbour lists in :mod:`atomlab.neighbors` are canonically ordered by
        central atom, which is what makes this the natural reduction here.
    n_segments : int
        Number of output rows.  Segments with no rows give exactly zero.

    Returns
    -------
    ndarray, shape (n_segments,) + values.shape[1:]

    Notes
    -----
    Implemented as a difference of cumulative sums rather than with
    ``np.add.at``, which is an order of magnitude slower on the array sizes
    this descriptor produces, and rather than with ``np.add.reduceat``, which
    silently returns the wrong thing for empty segments (an atom with no
    neighbours inside the cutoff, which is a legitimate state in a dilute gas).
    """
    if values.shape[0] == 0:
        return np.zeros((n_segments,) + values.shape[1:], dtype=values.dtype)
    if np.any(np.diff(segment) < 0):
        raise ValueError("segment labels must be sorted non-decreasing")
    counts = np.bincount(segment, minlength=n_segments)
    ends = np.cumsum(counts)
    starts = ends - counts
    cum = np.zeros((values.shape[0] + 1,) + values.shape[1:], dtype=np.float64)
    np.cumsum(values, axis=0, out=cum[1:])
    return cum[ends] - cum[starts]


